#!/usr/bin/env node
// The layer manifest: the real transfer size of every optional layer
// (src/layer-defs.js), measured from the built files in dist/. The Layers
// panel reads the result at run time (<data_dir>/layers.json); nobody types
// a size by hand. Ported from braga-3d (from lisboa-3d).
//
//   npm run build && node scripts/layers-manifest.mjs     write data/layers.json (and dist/data/layers.json)
//   node scripts/layers-manifest.mjs --check               exit 1 when data/layers.json is stale (npm run verify)
//   ... --city <id>                                        another city hosted here (data/<id>/layers.json)
//
// Transfer size = what Vercel (and scripts/perf-serve.mjs) sends: brotli
// at quality 11 (9 above 4 MB) for text files over 512 bytes, the raw bytes
// for the rest (JPEG, the .gz buildings). Bundle chunks are matched by name
// prefix in dist/static (their hash changes with every build).
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync, mkdirSync } from 'node:fs';
import { join, extname, dirname } from 'node:path';
import { brotliCompressSync, constants } from 'node:zlib';
import { LAYERS, CLASS_PRESET, PRESETS } from '../src/layer-defs.js';

const ROOT = join(import.meta.dirname, '..');
const args = process.argv.slice(2);
const opt = (k) => (args.includes(`--${k}`) ? args[args.indexOf(`--${k}`) + 1] : args.find((a) => a.startsWith(`--${k}=`))?.slice(k.length + 3));
const CHECK = args.includes('--check');
const DIST = join(ROOT, opt('dist') || 'dist');
const CITY_ID = opt('city') || process.env.CITY || 'porto';
const cfgPath = join(ROOT, 'cities', `${CITY_ID}.json`);
const CITY = existsSync(cfgPath) ? JSON.parse(readFileSync(cfgPath, 'utf8')) : {};
// as src/city.js: data/ for Porto, data/<id>/ for the other cities
const DATA_DIR = (CITY.data_dir || (CITY_ID === 'porto' ? 'data' : `data/${CITY_ID}`)).replace(/\/$/, '');
const OUT = join(ROOT, DATA_DIR, 'layers.json');

// the same rule as perf-serve.mjs
const COMPRESSIBLE = new Set(['.html', '.js', '.mjs', '.css', '.json', '.svg', '.txt', '.xml', '.webmanifest', '.bin']);
export function transferBytes(body, ext) {
  if (!COMPRESSIBLE.has(ext) || body.length <= 512) return body.length;
  return brotliCompressSync(body, { params: { [constants.BROTLI_PARAM_QUALITY]: body.length > 4e6 ? 9 : 11, [constants.BROTLI_PARAM_SIZE_HINT]: body.length } }).length;
}

function walk(dir) {
  if (!existsSync(dir)) return [];
  const out = [];
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out.push(...walk(p));
    else out.push(p);
  }
  return out;
}

function filesOf(layer) {
  const out = [];
  for (const f of layer.files) {
    // the data_dir of the city replaces the leading data/
    const rel = f.replace(/^data\//, `${DATA_DIR}/`);
    if (rel.endsWith('/**')) out.push(...walk(join(DIST, rel.slice(0, -3))));
    else if (existsSync(join(DIST, rel))) out.push(join(DIST, rel));
  }
  const missingChunks = [];
  for (const c of layer.chunks || []) {
    const dir = join(DIST, 'static');
    const hit = existsSync(dir) ? readdirSync(dir).filter((n) => n.startsWith(`${c}-`) && n.endsWith('.js')) : [];
    if (!hit.length) missingChunks.push(c);
    out.push(...hit.map((n) => join(dir, n)));
  }
  return { files: out, missingChunks };
}

function measure() {
  if (!existsSync(join(DIST, 'index.html'))) {
    console.error(`layers-manifest: ${DIST} has no build; run npm run build first`);
    process.exit(2);
  }
  const layers = {};
  for (const l of LAYERS) {
    const { files, missingChunks } = filesOf(l);
    if (missingChunks.length) {
      console.error(`layers-manifest: chunk(s) ${missingChunks.join(', ')} of layer ${l.id} not in dist/static`);
      process.exit(2);
    }
    let bytes = 0;
    let raw = 0;
    for (const f of files) {
      const body = readFileSync(f);
      raw += body.length;
      bytes += transferBytes(body, extname(f));
    }
    // name: the i18n source key (src/locales/ui.js has PT and EN);
    // defaultOn: per device class, from layer-defs.js CLASS_PRESET
    const defaultOn = Object.fromEntries(Object.entries(CLASS_PRESET).map(([cls, p]) => [cls, PRESETS[p].includes(l.id)]));
    layers[l.id] = { name: l.name, bytes, raw, files: files.length, defaultOn, ...(l.streamed ? { streamed: true } : {}), ...(l.liveExtra ? { liveExtra: true } : {}) };
  }
  return {
    _doc: 'Generated by scripts/layers-manifest.mjs from dist/ (do not edit). bytes: transfer size (brotli q11 for text, raw for JPEG and .gz, as Vercel sends them); raw: bytes on disk; files: how many files the layer can fetch. streamed: the bytes depend on the camera; the figure is every tile.',
    layers,
  };
}

const doc = measure();
const text = `${JSON.stringify(doc, null, 2)}\n`;
// --check: the same layers, files, flags and defaults, and sizes within 1 %
// or 4 KB. A bundle chunk imports the main chunk by its hashed name, so any
// change to the app moves the live chunks by a few bytes (138440 -> 138436
// after a CSS edit); the panel shows KB, so that is not a stale manifest.
// (braga-3d: many branches touch main.js; an exact match failed verify on each.)
function sameManifest(curText) {
  let cur;
  try {
    cur = JSON.parse(curText);
  } catch {
    return false;
  }
  const near = (a, b) => Number.isFinite(a) && Math.abs(a - b) <= Math.max(4096, b * 0.01);
  const strip = (v) => ({ ...v, bytes: 0, raw: 0 });
  const ids = Object.keys(doc.layers);
  if (JSON.stringify(Object.keys(cur.layers || {})) !== JSON.stringify(ids)) return false;
  return ids.every((id) => {
    const a = cur.layers[id];
    const b = doc.layers[id];
    return JSON.stringify(strip(a)) === JSON.stringify(strip(b)) && near(a.bytes, b.bytes) && near(a.raw, b.raw);
  });
}
if (CHECK) {
  const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (!sameManifest(cur)) {
    console.error(`layers-manifest: ${DATA_DIR}/layers.json is stale. Run: npm run build && node scripts/layers-manifest.mjs --city ${CITY_ID}`);
    for (const [id, v] of Object.entries(doc.layers)) console.error(`  ${id}: ${v.bytes} bytes (${v.files} files)`);
    process.exit(1);
  }
  console.log(`layers-manifest: ${DATA_DIR}/layers.json matches dist/`);
} else {
  writeFileSync(OUT, text);
  const distOut = join(DIST, DATA_DIR, 'layers.json');
  mkdirSync(dirname(distOut), { recursive: true });
  writeFileSync(distOut, text);
  for (const [id, v] of Object.entries(doc.layers)) console.log(`${id.padEnd(9)} ${(v.bytes / 1e6).toFixed(2).padStart(6)} MB transfer, ${(v.raw / 1e6).toFixed(2).padStart(6)} MB raw, ${v.files} files`);
  console.log(`wrote ${OUT} and ${distOut}`);
}
